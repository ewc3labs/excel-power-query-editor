#!/usr/bin/env node
// Generate docs/Config_Reference.md from package.json.
//
// WHY GENERATED. The hand-written CONFIGURATION.md documented thirteen settings that had been
// renamed, so anyone following it set keys that no longer existed. A reference maintained by hand
// drifts from the code it describes, silently, and the first person to notice is a confused user.
//
// This reads the single source of truth - contributes.configuration in package.json - so the
// reference cannot disagree with the software. Run it after changing any setting; CI checks that
// the committed file matches.

const fs = require('fs');
const path = require('path');

const PREFIX = 'excel-power-query-editor.';
const OUT = path.join(__dirname, '..', 'docs', 'Config_Reference.md');

/** Settings are grouped by their namespace, in the order a user meets them. */
const GROUP_ORDER = ['sync', 'watch', 'backup', 'log', 'symbols', 'xtn'];
const GROUP_TITLES = {
	sync: 'Sync',
	watch: 'Watch',
	backup: 'Backups',
	log: 'Logging',
	symbols: 'Excel symbols',
	xtn: 'Internal',
	'': 'Deprecated'
};
const GROUP_BLURBS = {
	sync: 'How, and where, your `.m` changes are written back.',
	watch: 'Syncing automatically when a file is saved.',
	backup: 'What is kept before a workbook is written, and for how long.',
	log: 'What the extension records, and where.',
	symbols: 'IntelliSense for Excel functions the M language service does not ship.',
	xtn: 'Written by the extension. Not intended to be set by hand.',
	'': 'Renamed in 0.6.0. Still read, still migrated, and removed after a release or two. '
		+ 'See [Config Changes](Config_Changes.md).'
};

function group(key) {
	const rest = key.slice(PREFIX.length);
	return rest.includes('.') ? rest.split('.')[0] : '';
}

function fmtDefault(v) {
	if (v === undefined) { return '_none_'; }
	if (v === '') { return '`""`'; }
	return '`' + JSON.stringify(v) + '`';
}

/** Strip the markdown link syntax VS Code uses for setting cross-references. */
function clean(text) {
	return String(text || '')
		.replace(/`#([^#]+)#`/g, (_, k) => '`' + k + '`')
		.replace(/\r?\n/g, ' ')
		.replace(/\s+/g, ' ')
		.trim();
}

function main() {
	const pkg = JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'package.json'), 'utf8'));
	const props = pkg.contributes.configuration.properties;

	const groups = new Map();
	for (const [key, def] of Object.entries(props)) {
		const g = group(key);
		if (!groups.has(g)) { groups.set(g, []); }
		groups.get(g).push([key, def]);
	}

	const order = [...GROUP_ORDER.filter(g => groups.has(g)), ...(groups.has('') ? [''] : [])];

	let out = `# Configuration Reference

Every setting this extension contributes, generated from \`package.json\` so it cannot drift from the
software. Settings are edited in VS Code's settings UI, or in \`settings.json\` using the full key.

Upgrading from 0.5.x? See [Config Changes](Config_Changes.md) — the settings were renamed, and your
existing values are migrated automatically.

`;

	for (const g of order) {
		out += `## ${GROUP_TITLES[g] ?? g}\n\n${GROUP_BLURBS[g] ?? ''}\n\n`;

		for (const [key, def] of groups.get(g).sort((a, b) => a[0].localeCompare(b[0]))) {
			const deprecated = def.deprecationMessage || def.markdownDeprecationMessage;
			out += `### \`${key}\`\n\n`;
			out += `| | |\n| --- | --- |\n`;
			out += `| Type | \`${def.type}\` |\n`;
			out += `| Default | ${fmtDefault(def.default)} |\n`;
			if (def.enum) { out += `| Values | ${def.enum.map(v => '`' + v + '`').join(' · ')} |\n`; }
			if (deprecated) { out += `| Status | **Deprecated** |\n`; }
			out += `\n${clean(def.markdownDescription || def.description)}\n\n`;
			if (deprecated) { out += `> ${clean(deprecated)}\n\n`; }
		}
	}

	out += `---\n\n_Generated by \`scripts/generate-config-reference.js\`. Do not edit by hand — `
		+ `change \`package.json\` and re-run \`npm run docs:config\`._\n`;

	const existing = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : null;

	if (process.argv.includes('--check')) {
		if (existing !== out) {
			console.error('docs/Config_Reference.md is out of date. Run: npm run docs:config');
			process.exit(1);
		}
		console.log('docs/Config_Reference.md is up to date.');
		return;
	}

	fs.writeFileSync(OUT, out, 'utf8');
	const count = Object.keys(props).length;
	console.log(`Wrote docs/Config_Reference.md — ${count} settings in ${order.length} groups.`);
}

main();
